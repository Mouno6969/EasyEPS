NORM_EXPLICIT.update({normalize(k): v for k, v in ROUND2.items()})


def fix_text(text: str) -> str | None:
    """Return the Bengali instruction for a question stem, or None if unchanged."""
    text = normalize(text)
    if HANGUL.search(text):
        for pattern, replacement in PREFIX_RULES:
            new = re.sub(pattern, replacement, text)
            if new != text:
                text = new
                break
        # exact match on normalized form
        norm = normalize(text)
        if norm in NORM_EXPLICIT:
            return NORM_EXPLICIT[norm]
        # mixed "Korean (বাংলা)" — prefer the Bengali gloss as the whole stem
        m = re.match(r"^\s*([^[\u0980-\u09ff]+?)\s*\(([\u0980-\u09ff][^()]*)\)\s*$", text)
        if m and HANGUL.search(m.group(1)):
            bn = m.group(2).strip()
            if not re.search(r"[।.!?]$", bn):
                bn += "।"
            return bn
        # still fully Korean from the start — needs a human translation
        if HANGUL.match(text.lstrip()):
            return None
        return text
    return None


def process_question(question: dict, key: str = "questionBn") -> bool:
    changed = False
    stem = question.get(key, "")
    fixed = fix_text(stem)
    if fixed and fixed != stem:
        question[key] = fixed
        changed = True
    # keep the authentic Korean instruction in questionKo
    ko = question.get("questionKo", "")
    new_stem = question.get(key, "")
    if HANGUL.search(new_stem) is None and (not ko.strip() or ko == stem):
        if HANGUL.search(stem):
            question["questionKo"] = stem
            changed = True
    return changed


def main() -> None:
    changed_files = 0
    unfixed: list[tuple[str, str, str]] = []
    for path in sorted(glob.glob("content/lessons/lesson-*.json")):
        data = json.loads(open(path, encoding="utf-8").read())
        touched = False
        for section in ("practice", "epsQuestions"):
            for q in data.get(section, []):
                before = q.get("questionBn", "")
                if process_question(q):
                    touched = True
                stem = q.get("questionBn", "")
                # verify: must not START with Hangul any more
                if HANGUL.match(stem.lstrip()):
                    unfixed.append((path, q.get("id", "?"), stem))
        if touched:
            changed_files += 1
            with open(path, "w", encoding="utf-8") as fh:
                json.dump(data, fh, ensure_ascii=False, indent=2)
                fh.write("\n")
    print(f"files changed: {changed_files}")
    print(f"unfixed stems: {len(unfixed)}")
    for path, qid, stem in unfixed:
        print(f"  {path} {qid}: {stem}")
    if unfixed:
        sys.exit(1)


